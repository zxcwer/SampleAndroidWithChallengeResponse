CREATE TABLE IF NOT EXISTS devices (
    device_id       VARCHAR(36)  PRIMARY KEY,
    public_key      VARCHAR(512) NOT NULL,
    key_fingerprint VARCHAR(64)  NOT NULL,
    status          VARCHAR(16)  NOT NULL,
    model           VARCHAR(128),
    registered_at   BIGINT       NOT NULL,
    last_auth_at    BIGINT
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_devices_key_fingerprint ON devices (key_fingerprint);

CREATE TABLE IF NOT EXISTS registration_codes (
    code_hash  VARCHAR(64) PRIMARY KEY,
    expires_at BIGINT      NOT NULL,
    used_at    BIGINT,
    created_by VARCHAR(128) NOT NULL
);

CREATE TABLE IF NOT EXISTS device_challenges (
    challenge_id VARCHAR(36) PRIMARY KEY,
    device_id    VARCHAR(36) NOT NULL,
    nonce        VARCHAR(64) NOT NULL,
    expires_at   BIGINT      NOT NULL,
    used_at      BIGINT
);
CREATE INDEX IF NOT EXISTS ix_device_challenges_expires_at ON device_challenges (expires_at);

CREATE TABLE IF NOT EXISTS auth_audit_logs (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id  VARCHAR(36),
    event      VARCHAR(32) NOT NULL,
    result     VARCHAR(16) NOT NULL,
    error_code VARCHAR(48),
    ip         VARCHAR(64),
    created_at BIGINT      NOT NULL
);
